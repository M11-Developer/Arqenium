import type {
  ChatRequest,
  ChatResponse,
  ModelInfo,
  ProviderCapabilities,
  ProviderConfig,
  ProviderHealth,
} from '../../../shared/types';
import type { AdapterContext, ProviderAdapter } from '../types';

/**
 * Deterministic demo adapter.
 *
 * Clearly labeled sample behavior - it is NOT a language model. It exists so
 * the full orchestration journey (tasks, tools, traces, evaluations) works out
 * of the box without any external credential. Every run created with this
 * provider is marked mode="demo" throughout the product.
 */
export class DemoAdapter implements ProviderAdapter {
  readonly kind = 'demo';

  capabilities(_cfg: ProviderConfig): ProviderCapabilities {
    return { streaming: false, toolCalling: true, vision: false, modelDiscovery: true, usageReporting: false };
  }

  async listModels(_cfg: ProviderConfig, _ctx: AdapterContext): Promise<ModelInfo[]> {
    return [{ id: 'demo-deterministic', name: 'Demo (sample data, not a real model)', contextWindow: 16_000 }];
  }

  async chat(cfg: ProviderConfig, req: ChatRequest, _ctx: AdapterContext): Promise<ChatResponse> {
    const last = req.messages[req.messages.length - 1];
    const userText = [...req.messages].reverse().find((m) => m.role === 'user')?.content ?? '';
    const toolResults = req.messages.filter((m) => m.role === 'tool');

    // Stage 2: a tool result came back - summarize it deterministically.
    if (last?.role === 'tool' || toolResults.length > 0) {
      const latest = toolResults[toolResults.length - 1];
      let observed = latest?.content ?? '';
      if (observed.length > 1200) observed = `${observed.slice(0, 1200)}... [truncated]`;
      return {
        message: {
          role: 'assistant',
          content:
            `Demo agent output (sample data - not generated by a real model).\n\n` +
            `Task context: ${userText.slice(0, 200)}\n\n` +
            `Observed tool result:\n${observed}\n\n` +
            `Next step for a real provider: review the observed data and produce the final answer.`,
        },
        model: cfg.defaultModel ?? 'demo-deterministic',
        usage: { tokensIn: 0, tokensOut: 0 },
        finishReason: 'stop',
      };
    }

    // Stage 1: request one read-only tool call so the pipeline exercises tools.
    if (req.tools?.length) {
      const pick =
        req.tools.find((t) => t.name === 'search_symbols') ??
        req.tools.find((t) => t.name === 'project_structure') ??
        req.tools.find((t) => t.name === 'search_files') ??
        req.tools[0];
      const query = userText.replace(/\s+/g, ' ').trim().slice(0, 80) || 'project';
      // Fill the tool's required parameters from its declared schema so the call
      // is always valid for the tool the agent actually has.
      const args: Record<string, unknown> = {};
      const schema = (pick.parameters ?? {}) as { properties?: Record<string, { type?: string }>; required?: string[] };
      const required = schema.required ?? Object.keys(schema.properties ?? {});
      for (const key of required) {
        const type = schema.properties?.[key]?.type;
        if (type === 'array') args[key] = key === 'paths' ? ['README.md'] : [];
        else if (type === 'number' || type === 'integer') args[key] = 5;
        else if (type === 'boolean') args[key] = false;
        else if (/^path$|Path$/i.test(key)) args[key] = 'README.md';
        else if (/^content$|^text$/i.test(key)) args[key] = `Demo content for: ${query}\n`;
        else args[key] = query;
      }
      if (pick.name === 'write_file' && typeof args.path === 'string' && !args.path.startsWith('demo/')) {
        args.path = 'demo/demo-agent-note.md';
        args.content = `Demo agent write (sample data, not a real model).\n\nTask: ${query}\n`;
      }
      return {
        message: {
          role: 'assistant',
          content: '',
          toolCalls: [{ id: 'demo_call_1', name: pick.name, arguments: JSON.stringify(args) }],
        },
        model: cfg.defaultModel ?? 'demo-deterministic',
        usage: { tokensIn: 0, tokensOut: 0 },
        finishReason: 'tool-calls',
      };
    }

    return {
      message: {
        role: 'assistant',
        content:
          `Demo agent output (sample data - not generated by a real model).\n` +
          `Received ${req.messages.length} message(s). Configure a real provider in Settings > Providers for live model responses.`,
      },
      model: cfg.defaultModel ?? 'demo-deterministic',
      usage: { tokensIn: 0, tokensOut: 0 },
      finishReason: 'stop',
    };
  }

  async health(_cfg: ProviderConfig, _ctx: AdapterContext): Promise<ProviderHealth> {
    return { ok: true, message: 'demo adapter available (sample data, no external calls)', latencyMs: 0 };
  }
}
